CREATE TABLE notifications (
  id uuid NOT NULL,
  api_key_id integer NOT NULL REFERENCES api_keys(id) ON DELETE CASCADE,
  notifiable_id text NOT NULL,
  type text NOT NULL,
  data jsonb NOT NULL,
  read_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (api_key_id, notifiable_id, id)
);

CREATE INDEX notifications_inbox_idx
  ON notifications (api_key_id, notifiable_id, created_at DESC);
CREATE INDEX notifications_unread_idx
  ON notifications (api_key_id, notifiable_id, created_at DESC)
  WHERE read_at IS NULL;

CREATE TABLE notification_jobs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  api_key_id integer NOT NULL REFERENCES api_keys(id) ON DELETE CASCADE,
  notification_id uuid NOT NULL,
  notifiable_id text NOT NULL,
  channel text NOT NULL CHECK (channel IN ('mail', 'sms')),
  payload jsonb NOT NULL,
  status text NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'processing', 'sent', 'failed')),
  attempts integer NOT NULL DEFAULT 0,
  run_after timestamptz NOT NULL DEFAULT now(),
  locked_at timestamptz,
  last_error text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (api_key_id, notifiable_id, notification_id, channel)
);

CREATE INDEX notification_jobs_pending_idx
  ON notification_jobs (run_after, created_at)
  WHERE status = 'pending';
