ALTER TABLE users
  ADD COLUMN IF NOT EXISTS accounts_sub text;

ALTER TABLE users
  ALTER COLUMN password DROP NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS users_accounts_sub_unique
  ON users (accounts_sub)
  WHERE accounts_sub IS NOT NULL;

CREATE TABLE admin_oidc_auth_requests (
  state_hash text PRIMARY KEY,
  nonce text NOT NULL,
  code_verifier text NOT NULL,
  redirect_uri text NOT NULL,
  return_to text NOT NULL,
  admin_user_id integer REFERENCES users(id) ON DELETE CASCADE,
  accounts_sub text,
  step_up boolean NOT NULL DEFAULT false,
  expires_at timestamptz NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX admin_oidc_auth_requests_expires_idx
  ON admin_oidc_auth_requests (expires_at);

CREATE TABLE admin_audit_log (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_user_id integer REFERENCES users(id) ON DELETE SET NULL,
  actor_accounts_sub text NOT NULL,
  actor_email text NOT NULL,
  action text NOT NULL,
  resource text NOT NULL,
  ip_address text NOT NULL,
  before_values jsonb,
  after_values jsonb,
  reason text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX admin_audit_log_created_at_idx
  ON admin_audit_log (created_at DESC);
CREATE INDEX admin_audit_log_resource_created_idx
  ON admin_audit_log (resource, created_at DESC);

